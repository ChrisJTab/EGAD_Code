#include <benchmarks/ycsb_submitter.h>
#include <benchmarks/ycsb_executor.h>

#include "ycsb_hybrid_stager.h"

namespace epic::ycsb {

class YcsbBenchmark : public Benchmark
{
public:
    YcsbConfig config;

    // Per-epoch txn batches, pre-generated by generateTxns()
    // at startup and host-resident for the lifetime of the run. For
    // paper-evaluation scenarios this doubles as the recovery input
    // log: every epoch's submit feeds from txn_array[epoch_id-1], so
    // recovery replay re-feeds the same batch unchanged. A production
    // deployment receiving txns dynamically would replace this vector
    // with a 2-epoch host ring buffer capturing each batch pre-submit;
    // out of scope for the paper.
    std::vector<TxnArray<YcsbTxn>> txn_array;
    TxnArray<YcsbTxn> index_input;
    TxnArray<YcsbTxnParam> index_output;
    TxnArray<YcsbTxnParam> initialization_input;
    TxnArray<YcsbExecPlan> initialization_output;
    TxnArray<YcsbTxnParam> execution_param_input;
    TxnArray<YcsbExecPlan> execution_plan_input;

    uint32_t * d_all_keys;
    uint32_t * d_read_keys;
    uint32_t * d_write_keys;


    TxnBridge input_index_bridge;
    TxnBridge index_initialization_bridge;
    TxnBridge index_execution_param_bridge;
    TxnBridge initialization_execution_plan_bridge;

    // CPU-side durable shadow of the key->CRID mapping. Owned here, with
    // a lifetime independent of the GPU index; YcsbGpuIndex holds a
    // reference to it.
    std::unique_ptr<YcsbCpuShadowIndex> cpu_shadow_;

    std::shared_ptr<YcsbIndex> index;
    std::shared_ptr<TableExecutionPlanner> planner;
    std::shared_ptr<YcsbSubmitter> submitter;
    std::shared_ptr<HybridStager> stager;

    YcsbVersionArrType CPU_versions;
    YcsbRecordArrType CPU_records;

    YcsbVersionArrType GPU_versions;
    YcsbRecordArrType GPU_records;

    std::shared_ptr<Executor> executor;

    std::shared_ptr<GpuAllocator> alloc_;

    explicit YcsbBenchmark(YcsbConfig config);
    ~YcsbBenchmark() override = default;

    void loadInitialData() override;
    void generateTxns() override;
    void runBenchmark() override;

    // Per-epoch pipeline (transfer/index/transfer/submit/
    // staging/init/transfer/execute/flush). Extracted from runBenchmark
    // so the same code path can be reused by the replay driver after a
    // GPU-crash reset. flush_inflight is passed by reference because the
    // stager hands one off across epochs (start_flush_epoch_async writes
    // it; the next epoch's sync_flush retires it). Caller owns the
    // FlushHandle lifetime.
    void runEpoch(uint32_t epoch_id, FlushHandle& flush_inflight);

    // Demote the Primary Store's dual-version tags >= min_discard_epoch
    // to 0 before replaying E-1, so replay reads the end-of-(E-2) base and
    // overwrites (not preserves) the discarded version. Sweeps all records (a
    // not-yet-inserted slot has tag 0, so it is a no-op). See tpcc_recovery.cpp's
    // rollbackPrimaryStoreVersions for the full rationale. Recovery path only.
    void rollbackPrimaryStoreVersions(uint32_t min_discard_epoch);

    // Current insert cursor (0 if not the GPU index). The two-epoch
    // hook tracks f_{E-2} across epochs from this.
    uint32_t currentInsertCount() const;

    // Current delete-log cursor (0 if not the GPU index or the mix has
    // no deletes). Tracked in the marker exactly like the insert cursor.
    uint32_t currentDeleteCount() const;

    // Advance the durable crash marker to `crash_epoch` and shift
    // the insert-cursor history (prev1<-current, prev2<-prev1). Called once per
    // epoch right after that epoch's writeback is queued/flushed, so the marker
    // reflects the in-flight writeback. No-op when recovery_meta_ is null
    // (non-durable runs stay byte-identical).
    void bumpRecoveryMarker(uint32_t crash_epoch);

    // GPU-state construction helpers, factored out of the ctor
    // (see ycsb.cpp).
    void initGpuPlannerAndSubmitter();
    void initGpuHybridStagerExecutor();

    // FNV-1a 64-bit hash over the byte range of CPU_records.
    // Used by 4d's correctness check: a no-crash baseline run and a
    // crash+replay run on the same workload should produce identical
    // hashes at end-of-run, proving replay reconstructs byte-identical
    // durable state.
    uint64_t hashCpuRecords() const;

    // Placement-invariant values-only digest of CPU_records, the
    // YCSB analog of TPCC's [STATE-HASH-VALMS]. Per record it folds the two
    // dual-version value slots in sorted (lower-bytes-first) order, ignoring
    // version tags and which physical slot holds each value. This is the
    // recovery gate for insert-bearing workloads (e.g. ycsbi): a GPU rebuild
    // legitimately reshuffles slot/placement, so the positional [STATE-HASH]
    // can differ across a reset while the logical content is identical. VALONLY
    // matching iff the logical database content matches.
    uint64_t hashCpuRecordsValOnly() const;

private:
    // Durable crash-recovery metadata (mmap-backed when
    // EPIC_DURABLE_STORE/RECOVER_FROM is set; null on normal runs -> no overhead).
    // crash_epoch is advanced to "the next epoch to run" each time an epoch's
    // writeback is queued (bumpRecoveryMarker), so on a crash it names the epoch E
    // whose predecessor's writeback is in-flight; recovery rolls the Primary Store
    // back to end-of-(E-2) and replays E-1 and E. The single cursor pair carries
    // f_{E-1}/f_{E-2} for the insert table (p2 == f_{E-2} = the rollback target;
    // YCSB-F has no inserts so both stay 0).
    // The banked publish (recovery_meta.h) keeps the epoch and the
    // cursors coherent when a fault kills the process mid-update. The
    // delete-log cursor pair is the insert pair's dual (d_p2 = deletes
    // durable at end-of-(E-2), the delete-side rollback target).
    struct YcsbRecoveryCursors {
        uint32_t free_start_p1; uint32_t free_start_p2;
        uint32_t del_p1; uint32_t del_p2;
    };
    using RecoveryMeta = BankedRecoveryMeta<YcsbRecoveryCursors>;
    static_assert(offsetof(RecoveryMeta, publish) % 8 == 0,
        "publish word must be 8-byte aligned for the single-store publish");
    RecoveryMeta* recovery_meta_ = nullptr;

    // Walk every insert-allocated CRID's slot in the CPU primary store and
    // confirm the executor's INSERT write reached CPU via writeback. Each
    // inserted slot must have at least one of {version1, version2} set to
    // a value in [1, config.epochs]; v1 == v2 == 0 means writeback was
    // never delivered (or never happened). Logs a single OK / FAILED line
    // plus up to 5 example failing CRIDs. Skipped for split_field=true and
    // for non-hybrid execution modes.
    void verifyInsertedRecords();

    // Verification-only negative-control hook. NO-OP unless
    // EPIC_RECOVERY_CORRUPT_ONE / EPIC_RECOVERY_SWAP_TWO is set; perturbs the
    // final CPU Primary Store right before the end-of-run state hashes.
    void corruptPrimaryStoreForNegControl();
};

} // namespace epic::ycsb

#endif // YCSB_H
